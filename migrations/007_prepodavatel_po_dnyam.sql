-- В КАКОЙ ДЕНЬ ПРИНИМАЮЩИЙ НЕ ПРИХОДИТ. Решение владельца 07.09, его словами:
-- «не бывает принимающего, который в разные дни в разных группах, такого никогда
-- не было… идея разных групп была в том, что в один из дней человек может
-- отсутствовать, а в другой день выбирается и фиксируется группа… можно сделать
-- проще: две кнопки-галочки — „в четверг прихожу“ и „в понедельник прихожу“, и
-- отдельно выбирается группа».
--
-- 🔴 ХРАНИТСЯ ОТСУТСТВИЕ, А НЕ ПРИСУТСТВИЕ, И ЭТО РЕШЕНИЕ, А НЕ ВКУС. Приходить —
-- обычное состояние принимающего; не приходить — исключение, которое кто-то
-- отметил. Храни мы присутствие, каждый НОВЫЙ преподаватель рождался бы «не
-- ходящим ни в один день», пока про него отдельно не вспомнят, — то есть пустая
-- таблица означала бы пустую школу. Здесь пустая таблица означает «все ходят
-- всегда», и это правда про 14 из 14 сегодня.
--
-- 🔴 ЗАЧЕМ ТАБЛИЦА, ЕСЛИ ДЕНЬ МОЖНО ВЫЧИСЛИТЬ ИЗ `enrollment`. Вычислить можно
-- только ОТРАЖЕНИЕ: «у него сегодня есть дети». Обратное — «он придёт, детей ему
-- ещё не дали» — не выразимо ничем, и галочка, поставленная в таком состоянии,
-- гасла бы при следующей перезагрузке страницы. Экран, который забывает то, что
-- на нём отметили, хуже экрана без этой отметки.
--
-- 🔴 ГРУППЫ ЗДЕСЬ НЕТ, И ЭТО ГЛАВНОЕ, ЧТО ЗАФИКСИРОВАНО ВЛАДЕЛЬЦЕМ: «он ходит
-- только в одну группу, за которой он фиксирован, но либо один, либо два дня».
-- Группа остаётся одна на человека (`teachers.gruppa`). Колонка `gruppa` в этой
-- таблице разрешила бы записать то, чего в школе не бывает, — и однажды это было
-- бы записано.
--
-- `slot` — тот же, что в `enrollment`: 1 понедельник, 2 четверг (миграция 003).
create table if not exists prepodavatel_ne_prihodit (
    teacher_id  integer not null references teachers(id),
    slot        integer not null check (slot between 1 and 7),
    primary key (teacher_id, slot)
);

-- ПЕРВОЕ ЗАПОЛНЕНИЕ — ТОЛЬКО ЯВНЫЕ ОТСУТСТВИЯ, И ОНИ ЧИТАЮТСЯ ИЗ ДАННЫХ. Человек,
-- у которого дети есть в ОДИН день и нет в другой, в тот другой не приходит: ровно
-- это и показывал экран до сегодняшнего дня. Человек, у которого детей нет вовсе,
-- не отсутствует — ему просто ещё никого не дали, и в таблицу он не попадает.
--
-- 🔴 БЕЗ `teachers.aktiven`: этой колонки нет в схеме, её заводит код
-- (`veb/server._obespechit_aktivnost`), и запрос о ней падает на любой чистой базе.
insert or ignore into prepodavatel_ne_prihodit (teacher_id, slot)
select vedushchie.teacher_id, dni.slot
from (select distinct teacher_id from enrollment where valid_to = '9999-12-31') vedushchie
cross join (select 1 as slot union all select 2) dni
where not exists (
    select 1 from enrollment e
    where e.teacher_id = vedushchie.teacher_id
      and e.slot = dni.slot
      and e.valid_to = '9999-12-31');
