-- УРОВЕНЬ РУКОВОДИТЕЛЯ. Цепочка, названная владельцем 2026-09-04:
--   школьник → преподаватель → РУКОВОДИТЕЛЬ → кабинет
--
-- ЗАЧЕМ СРЕДНИЙ УРОВЕНЬ, дословный смысл владельца: кабинет держится РУКОВОДИТЕЛЕМ,
-- а не преподавателем. Преподаватель заболел — школьник идёт в ТОТ ЖЕ кабинет,
-- потому что кабинет за руководителем и никуда не делся. В плоской модели
-- «преподаватель ↔ кабинет» это не выразить: пропал преподаватель — пропал кабинет.
--
-- ЧТО СТРОИМ СЕГОДНЯ: место для ПОСТОЯННОГО закрепления. Временное (болезнь,
-- разовый перевод) в этой волне НЕ делается, но дорога ему не закрыта: у
-- enrollment уже есть своя колонка `room`, и она перекрывает постоянную привязку
-- на конкретной строке. То есть постоянное живёт здесь, временное — там, и одно
-- другому не мешает.
--
-- ОТКУДА ВЗЯТЫ ДАННЫЕ. Не выдуманы: связка снята из живого enrollment запросом
--   select t.id, t.name, e.room from enrollment e join teachers t on t.id = e.teacher_id
--   where e.valid_to = '9999-12-31'
-- Каждый из 17 работающих преподавателей оказался ровно в ОДНОМ кабинете —
-- неоднозначности нет ни у кого. Кабинетов три: 203, 302, 303.
--
-- ИДЕМПОТЕНТНОСТЬ: обе таблицы через `if not exists`, наполнение через
-- `insert or ignore`. Прогон дважды подряд не плодит строк. Применяется yoyo,
-- который сам ведёт учёт применённого.
--
-- ОТКАТ: drop table kabinety; alter table teachers drop column kabinet;

create table if not exists kabinety (
    kabinet         text primary key,
    rukovoditel_id  integer references teachers(id),
    zametka         text
);

-- Кабинеты берутся из живых данных, а не из головы.
insert or ignore into kabinety (kabinet, rukovoditel_id, zametka)
select distinct room, null, 'заведён из enrollment при миграции 004'
from enrollment
where room is not null and valid_to = '9999-12-31';
