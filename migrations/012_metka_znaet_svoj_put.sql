--
-- 🔴 ПОЧЕМУ ОДНОГО ХОСТА ОКАЗАЛОСЬ МАЛО, И ЭТО НАЙДЕНО ПРОВЕРКОЙ НА ОБХОД, А НЕ
-- ПРИДУМАНО.  Миграция 011 связала род `боевая` с ИМЕНЕМ МАШИНЫ, и это ловит копию,
-- УНЕСЁННУЮ на другую машину.  Копию, снятую `cp` НА ТОЙ ЖЕ МАШИНЕ, она не ловит
-- вовсе: хост совпадает, слово «боевая» уехало вместе с байтами, и дверь источника
-- отвечает `вердикт: БОЕВАЯ, СВЕЖАЯ, СВОЯ ✅` про файл, который боевым не является.
-- Прогон, которым это снято (та же машина, тот же час):
--
--     $ cp boevaya.db chestnaya-cp.db
--     $ SPETSMAT_BAZA=chestnaya-cp.db python3 core/istochnik.py
--     род: боевая · помечена на MacBook-Air-IVAN-2.local · вердикт: БОЕВАЯ, СВЕЖАЯ, СВОЯ ✅
--
-- А на сервере `cp` делается именно на той машине, где боевая и живёт, — то есть
-- дыра открыта ровно там, где база настоящая.  Задание требовало от метки, чтобы
-- «копия не назвала себя боевой ДАЖЕ СЛУЧАЙНО»; случайный `cp` рядом с боевой — это
-- и есть тот случай.
--
-- ЧТО ЗАКРЫВАЕТ ЭТА КОЛОНКА.  Метка теперь помнит АБСОЛЮТНЫЙ ПУТЬ файла, для которого
-- она поставлена.  `core/istochnik.py::proverit_metku` сверяет его с путём, который
-- соединение НА САМОМ ДЕЛЕ открыло (`PRAGMA database_list`, не настройка).  Копия
-- лежит по другому пути по определению — иначе она не копия, а тот же файл, — поэтому
-- `cp` где угодно и под каким угодно именем даёт файл, чья метка указывает не на него.
--
-- 🔴 ЧЕГО ЭТО ПО-ПРЕЖНЕМУ НЕ ДЕЛАЕТ, И ГОВОРИТЬ ОБ ЭТОМ НАДО ВСЛУХ.  Метка — НАДПИСЬ
-- ВНУТРИ ФАЙЛА, а не подпись.  Кто может писать в файл, тот может и переписать метку:
-- проверено той же проверкой на обход (`update istochnik_metka set rod='боевая', host=…`
-- → дверь отвечает зелёным).  Защиты от НАМЕРЕНИЯ здесь нет и не может быть без ключа,
-- которого у этого проекта нет.
--
-- 🔴 ПОПРАВКА ОРКЕСТРАТОРА 10.09, ПОСЛЕ ПРОВЕРКИ НА ОБХОД.  Здесь стояло: «защита от
-- НЕБРЕЖНОСТИ — `cp`, `rsync`, ВОССТАНОВЛЕННЫЙ СНИМОК, забытая копия — ПОЛНАЯ».  Это
-- НЕВЕРНО, и неверна ровно та часть, которую легче всего принять на веру.  Замерено
-- проверкой на обход: снимок, положенный ОБРАТНО НА СВОЙ ПУТЬ, неотличим от живой базы —
--     cp boevaya.db snimok.db      # снимок: 1 отметка
--     (жизнь идёт, в боевой стало 2)
--     cp snimok.db boevaya.db      # небрежное восстановление
--     → вердикт «БОЕВАЯ, СВЕЖАЯ, СВОЯ ✅», rc=0, а отметка потеряна.
-- Метка привязана к ПУТИ, а не к содержимому, поэтому старый снимок на правильном пути
-- она подтверждает.  От `cp` В ДРУГОЕ МЕСТО защита действительно полная (проверено: шесть
-- вариантов из шести отбиты); от возврата снимка НА МЕСТО — нет.
-- Обещание исправлено, а не удалено: строка, обещающая больше, чем механизм даёт, опаснее
-- отсутствующей — ей верят вместо того, чтобы проверить.  Это тот же класс, что «гейт,
-- молчащий по промаху», только с другой стороны: инструмент, обещающий по промаху.
--
-- ПОЧЕМУ `alter table ... add column`, А НЕ ПЕРЕСБОРКА (ср. 010, где таблицу
-- пересобирали).  Там расширяли CHECK, а SQLite не умеет снимать ограничение иначе.
-- Здесь нужна НОВАЯ КОЛОНКА, и `add column` даёт её, не тронув ни одной строки.
-- Пустая строка по умолчанию значит «путь не записан» — так выглядит метка, поставленная
-- до этой миграции, и такая метка боевой себя назвать уже не сможет: см. `proverit_metku`.

alter table istochnik_metka add column put text not null default '';
