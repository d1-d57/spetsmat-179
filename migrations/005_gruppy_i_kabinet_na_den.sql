-- Прошлая (004) была ПЕРЕВЁРНУТА: там кабинет висел на преподавателе. Владелец:
-- «система обратная».
--
-- КАК УСТРОЕНО НА САМОМ ДЕЛЕ:
--   школьник → преподаватель → ГРУППА (старший) → кабинет НА ДЕНЬ
--
-- Групп три, они же старшие, и это ПОСТОЯННАЯ величина:
--   ИЯ — Ваня Яковлев · ДМ — Даня Макаров · НС — Наталия Стрелкова
-- Преподаватель закреплён за группой на год и почти не меняется.
--
-- 🔴 КАБИНЕТ НЕ ПОСТОЯНЕН И НЕ ПРИНАДЛЕЖИТ ПРЕПОДАВАТЕЛЮ. Он назначается ГРУППЕ
-- на КОНКРЕТНЫЙ ДЕНЬ и меняется: «могут меняться и дни, и недели, и время уроков».
-- Привязку на завтра владелец ставит накануне вечером. Поэтому кабинет — не ключ,
-- а отдельная строка на дату, и её отсутствие законно: завтрашней ещё нет.
--
-- ЗАНЯТИЯ У ВСЕХ ГРУПП ОДНОВРЕМЕННО — из этого следует, что кабинет на дату
-- у группы ровно один.

create table if not exists gruppy (
    kod       text primary key,        -- ИЯ · ДМ · НС
    starshij  text not null            -- Ваня Яковлев · Даня Макаров · Наталия Стрелкова
);

insert or ignore into gruppy (kod, starshij) values
    ('ИЯ', 'Ваня Яковлев'),
    ('ДМ', 'Даня Макаров'),
    ('НС', 'Наталия Стрелкова');

-- Кабинет группы НА ДЕНЬ. Нет строки на дату — кабинет на этот день не назначен,
-- и это нормальный случай, а не потеря данных.
create table if not exists kabinet_na_den (
    data      text not null,           -- ГГГГ-ММ-ДД
    gruppa    text not null references gruppy(kod),
    kabinet   text not null,
    primary key (data, gruppa)
);
