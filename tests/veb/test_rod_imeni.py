"""Род человека по его имени — `veb/obshchee/karkas.py::rod_imeni` · `v_rode`.

🔴 ПОЧЕМУ ЭТОТ ФАЙЛ ВООБЩЕ ЕСТЬ. Владелец 11.09, глядя на живой журнал: *«опять у
тебя „принял Саша Оревкова“. Ну пол учитывай»*. Пола в схеме нет ни у `teachers`,
ни у `students` — он ВЫВОДИТСЯ, а выведенное правило обязано сторожиться на тех
самых именах, на которых оно ломается, а не на удобных.

Имена ниже — с БОЕВОЙ базы, не выдуманные: девятнадцать преподавателей и те
школьники, на которых простое правило «имя на -а/-я значит женское» отвечает
неверно.
"""

from __future__ import annotations

import pytest

from veb.obshchee.karkas import rod_imeni, v_rode


#: (имя, фамилия, род). Фамилия пустая — значит человек так и записан, одним словом.
LYUDI = [
    # Пять случаев, на которых ломается правило «-а/-я значит женское»: четверо
    # мужчин с уменьшительными именами и женщина с двуполым именем.
    ("Ваня Яковлев", "", "м"),
    ("Даня Макаров", "", "м"),
    ("Дима Елисеев", "", "м"),
    ("Вася", "", "м"),
    ("Саша Оревкова", "", "ж"),
    # Фамилия несклоняемая — отвечает имя.
    ("Елена Мирошниченко", "", "ж"),
    ("Наталья Амбург", "", "ж"),
    ("Михаил Шнитке", "", "м"),
    ("Александр Тертерян", "", "м"),
    ("Ян Маршалл", "", "м"),
    # Обычные склоняемые фамилии.
    ("Ольга Рыжая", "", "ж"),
    ("Настя Вахрина", "", "ж"),
    ("Наталия Стрелкова", "", "ж"),
    ("Андрей Рябичев", "", "м"),
    # Одним словом, без фамилии вовсе.
    ("Вика", "", "ж"),
    ("Надя", "", "ж"),
    ("Полина", "", "ж"),
    # Школьники: у них хранится `surname` + `name`, то есть ПОРЯДОК ОБРАТНЫЙ, и
    # фамилию приходится называть отдельно. Без этого «Фефелов Иван» разобрался бы
    # по слову «Иван» как по фамилии.
    ("Иван", "Фефелов", "м"),
    ("Ирина", "Агаркова", "ж"),
    ("Анастасия", "Аникина", "ж"),
    ("Василий", "Бирюков", "м"),
    ("Софья", "Гамаюнова", "ж"),
    # Единственное имя боевой базы, которое правило русских окончаний читает
    # неверно: фамилия несклоняемая, имя грузинское женское на -о.
    ("Нино", "Кахиани", "ж"),
]


@pytest.mark.parametrize("imya,familiya,ozhidaem", LYUDI)
def test_rod_opredelyaetsya_po_familii_a_potom_po_imeni(imya, familiya, ozhidaem):
    assert rod_imeni(imya, familiya) == ozhidaem, (imya, familiya)


def test_familia_silnee_imeni_i_eto_ne_sluchajnost():
    """«Саша Оревкова» и «Саша Иванов» — одно имя, разный род, решает фамилия."""
    assert rod_imeni("Саша Оревкова") == "ж"
    assert rod_imeni("Саша Иванов") == "м"


def test_nikogo_ne_nazvali_rod_ne_pridumyvaetsya():
    assert rod_imeni("") is None
    assert rod_imeni("   ") is None


def test_v_rode_stavit_slovo_i_padaet_v_nemarkirovannoe():
    assert v_rode("Саша Оревкова", "принял", "приняла") == "приняла"
    assert v_rode("Ваня Яковлев", "принял", "приняла") == "принял"
    assert v_rode("Ирина", "не был", "не была", "Агаркова") == "не была"
    # Человек не назван вовсе — мужское, немаркированное; это единственный случай,
    # когда выбор делается не по данным, и он назван вслух.
    assert v_rode("", "принял", "приняла") == "принял"
