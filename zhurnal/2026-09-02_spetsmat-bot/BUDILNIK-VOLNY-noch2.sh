#!/bin/bash
# ═══════════════════════════════════════════════════════════════════════════
# БУДИЛЬНИК ВОЛНЫ noch2 — ОПОВЕЩЕНИЕ. Запускать ТОЛЬКО задачей оснастки
# (`run_in_background`), НЕ nohup: весь его смысл в том, что его ВЫХОД —
# сигнал голове. Под nohup он переживёт зависание приложения и НЕ РАЗБУДИТ
# НИКОГО, то есть станет бесполезен ровно в том, ради чего заведён.
#
# 🔴 ТРИ МЕХАНИЗМА ВОЛНЫ, ТРИ РАЗНЫЕ СМЕРТИ, НИ ОДИН НЕ ЗАМЕНЯЕТ ДРУГИХ:
#   1. CHASOVOJ-VOLNY-noch2.sh — nohup, ppid=1: переживает зависание,
#      поднимает мёртвую ГОЛОВУ через `claude -p`. НЕ БУДИТ живую.
#   2. ЗАХОДЫ под nohup        — переживают сессию, работают сами.
#   3. ЭТОТ файл               — задача оснастки: будит, но умирает вместе
#      с приложением.
#
# 🔴 ЦЕНА, ОПЛАЧЕННАЯ ЭТИМ ФАЙЛОМ 02.09 09:15, СОРОК МИНУТ.
# Первая версия считала окна так:
#     pgrep -f "$ARKA/ZAPUSK-ZAHODA.sh" | grep -vc BUDILNIK || echo 0
# При нуле окон `grep -vc` печатает «0» И выходит кодом 1, поэтому `|| echo 0`
# дописывает ВТОРОЙ «0». Переменная становится «0\n0», сравнение
# `[ "$O1" -lt "$O0" ]` падает «integer expression expected» в stderr и даёт
# ЛОЖЬ — то есть ветка «окно умерло» не срабатывает НИКОГДА.
# P1 умерла в 08:36 с «API Error: Connection lost mid-response», будильник
# вышел кодом 3 «тик без событий» в 09:15, и волна простояла сорок минут при
# полностью живой оснастке. Тот же дефект был найден и починен в часовом за
# час до этого — и не перенесён сюда. Отсюда форма ниже: считаем через `ps`
# (у macOS pgrep нет `-c` вовсе), код возврата гасим, результат чистим `tr -d`.
#
# 🔴 ОДНОРАЗОВЫЙ. После каждого срабатывания ВЗВЕСТИ ЗАНОВО.
#
# 🔴 ВЗВОДИТЬ ТРИ ЛЕСЕНКОЙ — 600, 1200, 1800, — А НЕ ОДИН.
# ЦЕНА ОДНОГО, оплачена дважды за вечер 02.09: 36 минут простоя в 16:19 и
# 43 минуты в 19:39 → 20:23. Оба раза механизм был исправен, и оба раза
# голова просто НЕ ВЗВЕЛА его заново, увлёкшись работой. Взведение — ЕДИНСТВЕННЫЙ
# шаг всей оснастки, который держится на памяти головы, и он отказал дважды.
# Соседние волны устроены так же и лучше не решают: их будильник стоит на 3000 с.
# Поэтому здесь не дисциплина, а ИЗБЫТОЧНОСТЬ: три задачи оснастки, заведённые
# ОДНИМ ходом, дают три независимых пробуждения. Забытое взведение стоит тогда
# 10 минут вместо сорока, а два забытых подряд — 20.
# Просьба владельца 02.09 20:2x, дословно: «Тебе нужно раз в 10 минут
# просыпаться, смотреть, что происходит».
#
# 🔴 ЦЕНА НЕВЗВЕДЁННОГО БУДИЛЬНИКА, 02.09: ДВА ЧАСА БЕЗ БУДИЛЬНИКА, 36 МИНУТ ПРОСТОЯ.
# Последняя запись в логе — 14:34:52 «ЖДЁТ ПРИЁМКИ: kod_P17». После неё голова
# не взвела его НИ РАЗУ. В 16:19 ход кончился, будить стало некому, и волна
# простояла до 16:55, когда позвал владелец. Часовой при этом работал
# безупречно и молчал ПРАВИЛЬНО: его порог — 90 минут и его дело — СМЕРТЬ.
# ГОЛОВА БЫЛА ЖИВА И НЕ ДЕЛАЛА НИЧЕГО, а такого отказа не ловил никто.
# Отсюда два разных порога для двух разных отказов:
#     ПРОСТОЙ — этот файл, 720с (12 мин), будит живую голову
#     СМЕРТЬ  — часовой, 90 мин, поднимает новую взамен умершей
# Цена простоя — не потерянная работа, а ЗАДЕРЖКА ПРИЁМКИ: в те же 36 минут
# пять окон заходов закрылись (замер часового: 16:30 «окон 6» → 16:50 «окон 1»),
# и готовые позиции лежали непринятыми, потому что принимать было некому.
#
# 🔴 ПОЧЕМУ «ОКОН СТАЛО МЕНЬШЕ» СЧИТАЕТСЯ ЗДЕСЬ, А НЕ У ЧАСОВОГО.
# Владелец 02.09 17:0x попросил, чтобы будил ЧАСОВОЙ. Часовой этого не может:
# он живёт под nohup с ppid=1, вне сессии, и единственный его способ обратиться
# к голове — поднять НОВУЮ через `claude -p`. Над живой головой это две головы,
# пишущие в одни файлы. Разбудить ЖИВУЮ умеет ровно один механизм — задача
# оснастки, то есть этот файл, потому что голову будит его ВЫХОД.
# Поэтому событие стоит здесь и меряется КАЖДЫЕ 60 с вместо 300 с у часового:
# сигнал «заход вернулся» приходит впятеро быстрее, чем если бы часовой мог.
# Часовой ту же убыль пишет в пульс отдельной строкой — чтобы факт пережил
# смерть головы и достался следующей.
#
# 🔴 СЕРДЦЕ БЬЁТСЯ КАЖДЫМ ОБРАЩЕНИЕМ К BASH, А НЕ «КАЖДЫМ ХОДОМ». Ход головы
# бывает длиннее порога простоя; при ударе раз в ход молчание сердца не отличает
# «простаиваю» от «занят долгой командой», и порог в 12 минут стал бы врать.
#
# 🔴 ТИК ОБЯЗАН БЫТЬ СИЛЬНО МЕНЬШЕ ПОРОГА СМЕРТИ ЧАСОВОГО. Сердце бьёт голова,
# а голова бьёт его только НА СВОЁМ ХОДУ; ход начинается от выхода будильника.
# Тик 2400с при пороге 45м оставлял пять минут запаса — часовой чуть не поднял
# вторую голову поверх живой. Сейчас: тик 1200с, порог часового 90м.
#
# КОДЫ ВЫХОДА:
#   0 — заход ЖДЁТ ПРИЁМКИ (отчёт закрыт хэшем, вердикта нет)
#   1 — 🔴 ПУЛЬС ЧАСОВОГО НЕ РАСТЁТ: часового НЕТ, что бы ни говорили процессы
#   2 — 🔴 ОБРЫВ: окон заходов нет, а незакрытый заход есть — нужен добор
#   3 — тик без событий: взвести заново
#   4 — 🔔 ОКОН СТАЛО МЕНЬШЕ, ЧЕМ ПРИ ВЗВЕДЕНИИ: заход вернулся, ЕСТЬ ЧТО ПРИНИМАТЬ
# ═══════════════════════════════════════════════════════════════════════════
set -u
ARKA="$HOME/Documents/GitHub/spetsmat-bot/zhurnal/2026-09-02_spetsmat-bot"
PULS="$ARKA/PULS-CHASOVOGO-noch2.log"
LOG=/tmp/budilnik-noch2.log
TIK=${1:-300}           # ПОТОЛОК ПРОСТОЯ. 12 мин: владелец 02.09 16:55 — ловить ПРОСТОЙ головы, а не только смерть
SVERKA=${2:-420}        # через сколько секунд сверить РОСТ пульса (> периода часового 300с)
GRACE=${3:-120}         # сколько секунд после старта не судить обрыв (окно ещё поднимается)

krugov () { grep -c '^....-..-.. ..:..:.. круг ' "$PULS" 2>/dev/null || echo 0; }
metka ()  { stat -f %m "$PULS" 2>/dev/null || stat -c %Y "$PULS" 2>/dev/null || echo 0; }

# Темы ЭТОЙ арки — по файлам-заходам, а не списком в коде: список в коде
# отстал бы от волны на любой новой позиции.
# 🔴 ТОЛЬКО ПОЗИЦИИ ЭТОЙ ВОЛНЫ, А НЕ ВСЕ `kod_*.md` АРКИ.
# ЦЕНА, ОПЛАЧЕНА 10.09 00:50, ТРИ БУДИЛЬНИКА ЗА ОДНУ МИНУТУ. Арка живёт с 02.09
# и накопила 71 файл-заход восьми прошлых волн. Глоб `kod_*.md` брал их все, и
# СОБЫТИЕ 1 срабатывало на `kod_N0-dovezti-rabotu-noch-0904.md` — позиции волны
# от 04.09, чей отчёт давно закрыт хэшем, а вердикт в её мандате, не в поле
# `## ФАЗА ПРИЁМКИ` этого файла. Все три будильника, взведённые лесенкой
# 600/1200/1800, вышли кодом 0 через 60 с каждый: механизм, который один умеет
# будить ЖИВУЮ голову, был мёртв с первой минуты волны и будил бы её на
# прошлогоднюю работу вечно. Отсюда список позиций ФАЙЛОМ `VOLNA-POZICII`,
# а глоб — только запасной путь, когда файла нет.
POZICII="$ARKA/VOLNA-POZICII"
fajly_volny () {
  if [ -s "$POZICII" ]; then
    while IFS= read -r t; do
      t=$(printf '%s' "$t" | tr -d ' \r')
      [ -n "$t" ] || continue
      case "$t" in \#*) continue;; esac
      [ -e "$ARKA/kod_$t.md" ] && printf '%s\n' "$ARKA/kod_$t.md"
    done < "$POZICII"
  else
    for f in "$ARKA"/kod_*.md; do [ -e "$f" ] && printf '%s\n' "$f"; done
  fi
}
temy_arki () { fajly_volny | while IFS= read -r f; do b=$(basename "$f" .md); printf '%s ' "${b#kod_}"; done; }

# Окна заходов ЭТОЙ арки.
okon () {
  # 🔴 НЕ `pgrep -c`: у macOS pgrep ФЛАГА `-c` НЕТ ВОВСЕ — вызов падает
  # с usage, а `|| echo 0` превращает падение в честный на вид ноль.
  # Замер 02.09 09:18: `ps` показывает живое окно pid 60790, а
  # `pgrep -cf ZAPUSK-ZAHODA` отвечает 0 на ЛЮБОЙ образец.
  # 🔴 И привязка к СВОЕЙ арке обязательна: рядом идут окна соседних волн
  # (замер: `bash ./ZAPUSK-ZAHODA.sh zhivost-volny-3 sonnet --dobor`),
  # и голый образец «ZAPUSK-ZAHODA.sh» считал бы чужую работу своей.
  # 🔴 И СЕБЯ ИСКЛЮЧИТЬ: строка поиска попадает в командную строку САМОГО grep,
  # и он находит себя. Замер 02.09 09:20: живое окно одно, счётчик отвечал 2,
  # вторая строка — собственный `ugrep`. Ровно урок волны 6 («pgrep матчит сам
  # себя, и форма без исключения ждёт вечно»). Отсюда `$1 == "bash"`: окно
  # заходa — это ВСЕГДА `bash <путь>/ZAPUSK-ZAHODA.sh <тема> <модель>`.
  # 🔴 ДВА КАНАЛА ЗАПУСКА, И СЧИТАТЬ НАДО ОБА. Платная позиция идёт
  # `bash <арка>/ZAPUSK-ZAHODA.sh`, бесплатная — `python3 .../orkestr.py <арка>
  # --rezhim progon` (мандат: бесплатное руками не пускают). Счётчик по одному
  # каналу объявил бы ОБРЫВ, пока во втором идёт живая работа.
  # 🔴 И ОТНОСИТЕЛЬНЫЙ ЗАПУСК ТОЖЕ СВОЙ. Замер 02.09 16:57: добор P15 был пущен
  # как `cd <арка> && bash ZAPUSK-ZAHODA.sh P15-tekst opus --dobor`, и в `ps`
  # его вторым полем стоит ГОЛОЕ ИМЯ файла. Сравнение с полным путём давало по
  # живому окну ноль — то есть будильник объявил бы ОБРЫВ над работающим
  # заходом. Это тот же класс, что «зона-префикс даёт ложно-зелёное»: образец
  # не совпал ни с чем, и молчание было принято за факт.
  # Голое имя считаем СВОИМ только вместе с темой из наших `kod_*.md` — иначе
  # относительный запуск соседней волны попал бы к нам в счёт.
  ps -Ao command= 2>/dev/null \
    | awk -v z="$ARKA/ZAPUSK-ZAHODA.sh" -v a="$ARKA" -v temy="$(temy_arki)" '
        BEGIN { split(temy, q, " "); for (i in q) svoi[q[i]] = 1 }
        ($1 == "bash" && ($2 == z || $2 == "ZAPUSK-ZAHODA.sh") && ($3 in svoi)) { n++ }
        (index($0, "orkestr.py " a) && index($0, "--rezhim progon")) { n++ }
        END { print n+0 }' \
    | tr -d ' \n'
}

# Идёт ли окно ИМЕННО ЭТОГО захода. Два канала запуска, два места, где стоит тема:
#   платная   — `bash <арка>/ZAPUSK-ZAHODA.sh <тема> <модель> [--dobor]`
#   бесплатная — `python3 .../orkestr.py <арка> … --zahody kod_<тема>.md`
zahod_idyot () {
  ps -Ao command= 2>/dev/null | awk -v t="$1" -v z="$ARKA/ZAPUSK-ZAHODA.sh" -v a="$ARKA" '
      ($1 == "bash" && ($2 == z || $2 == "ZAPUSK-ZAHODA.sh") && $3 == t) { found = 1 }
      (index($0, "orkestr.py " a) && index($0, "--zahody kod_" t ".md")) { found = 1 }
      END { exit found ? 0 : 1 }'
}

# Заход считается ЗАКРЫТЫМ, если в его `## ОТЧЁТ` есть хэш коммита или прямое
# «коммита нет». Заголовок доказательством НЕ считается: он стоит в каркасе с
# рождения, и сторож соседней волны, судивший по заголовку, объявил 22 готовых
# из 22 при нуле написанных отчётов.
# 🔴 НЕ `awk '/^## ОТЧ[ЕЁ]Т/'`. `Ё` в скобочном классе — ДВА БАЙТА, а awk
# сравнивает в классе БАЙТЫ: образец требует один символ из набора между «ОТЧ»
# и «Т» и не совпадает НИКОГДА. Замер 02.09 09:39 на живом kod_P1-yadro.md:
# скобочная форма → 0 строк, `index($0,"## ОТЧ")==1` → 179 строк. Из-за этого
# будильник объявил ОБРЫВ (код 2) над заходом, который только что закончил и
# закрыл отчёт хэшем, — то есть велел добить готовую работу.
# ⚠ Тот же дефект живёт в BUDILNIK-VOLNY-9.sh соседней волны, строки 61 и 64:
# там ветка «ждёт приёмки» не может сработать вовсе. Их файл не наш — заявка.
sekcia () { awk -v h="$2" 'index($0,h)==1{x=1;next} index($0,"## ")==1{x=0} x' "$1"; }

# 🔴 ЗАКРЫТ = ЗАПОЛНЕНА ФОРМАЛЬНАЯ СТРОКА `**КОММИТ:**`, а не «в отчёте где-то
# есть хэш». Замер 02.09 10:46: заход P2 ещё РАБОТАЛ (окно живо 57 минут), но в
# теле отчёта уже цитировал свои коммиты — будильник объявил «ждёт приёмки»,
# приёмка пошла и дала 14 гейтов из 18, потому что шапка отчёта не дописана.
# Ранняя приёмка над живым заходом — это гонка: аналитик пишет вердикт в файл,
# в который исполнитель прямо сейчас пишет отчёт.
zahod_zakryt () {
  local F="$1" STR
  # 🔴 ЯКОРЬ В НАЧАЛЕ СТРОКИ, И БЕРЁМ ПОСЛЕДНЮЮ. `grep -m1 'КОММИТ:'` ловит
  # УПОМИНАНИЕ строки внутри прозы отчёта раньше самой строки: заход P6 в доборе
  # объяснял, что «три машинно-читаемых строки каркаса (`**АРТЕФАКТ:**`,
  # `**РОД АРТЕФАКТА:**`, `**КОММИТ:**`) несли плейсхолдеры» — и предикат счёл
  # заполненный отчёт незакрытым (замер 02.09 13:37: настоящая строка стояла
  # 17-й, а поймана была 5-я). Ровно тот же класс, что «первое совпадение»
  # у `grep -m1` в проверке вердикта.
  STR=$(sekcia "$F" "## ОТЧ" | grep '^\*\*КОММИТ:\*\*' | tail -1)
  [ -n "$STR" ] || return 1
  # ⚠ «есть `<` ⇒ плейсхолдер» — СЛИШКОМ ГРУБО и уже дало ложное красное:
  # честный отчёт P1 цитирует внутри своей же строки форму команды
  # `git_zona.py check --zone <зона>`, и признак объявил принятую позицию
  # незакрытой. Хватает требования ХЭША в бэктиках на самой строке: шаблон
  # каркаса несёт `<хэш>`, который под шестнадцатеричный образец не подходит.
  printf '%s' "$STR" | grep -qE '`[0-9a-f]{7,40}`' && return 0
  printf '%s' "$STR" | grep -qiE 'КОММИТА НЕТ|NO COMMIT'  && return 0
  return 1
}

K0=$(krugov); M0=$(metka); OKON0=$(okon)
echo "$(date '+%H:%M:%S') · взведён · пульс: кругов $K0 · окон $OKON0 · тик ${TIK}с" >> "$LOG"
NACHALO=$(date +%s); SVERENO=0

while :; do
  sleep 60
  PROSHLO=$(( $(date +%s) - NACHALO ))

  # ── ГЛАВНОЕ: часовой доказывается РОСТОМ ПУЛЬСА, а не наличием процесса.
  #    Жив был и тот сторож, который никого не будил.
  if [ "$SVERENO" -eq 0 ] && [ "$PROSHLO" -ge "$SVERKA" ]; then
    K1=$(krugov); M1=$(metka)
    if [ "$K1" -gt "$K0" ] && [ "$M1" -gt "$M0" ]; then
      echo "$(date '+%H:%M:%S') · ✅ ПУЛЬС РАСТЁТ: кругов ${K0}→$K1 за ${PROSHLO}с — часовой ЕСТЬ" >> "$LOG"
      SVERENO=1
    else
      echo "$(date '+%H:%M:%S') · 🔴 ПУЛЬС НЕ РАСТЁТ за ${PROSHLO}с: кругов ${K0}→$K1, метка ${M0}→$M1 — ЧАСОВОГО НЕТ" >> "$LOG"
      exit 1
    fi
  fi

  # ── СОБЫТИЕ 1: заход закрыл отчёт хэшем, вердикта в ФАЗЕ ПРИЁМКИ нет ⇒ ждёт приёмки
  while IFS= read -r F; do
    [ -e "$F" ] || continue
    zahod_zakryt "$F" || continue
    # 🔴 ЗАКРЫТЫЙ ОТЧЁТ ПРИ ЖИВОМ ОКНЕ — НЕ «ЖДЁТ ПРИЁМКИ», А ДОБОР В РАБОТЕ.
    # Замер 02.09 10:54: добор P2 дописал строку `**КОММИТ:**` на второй минуте
    # и продолжил работать; будильник разбудил голову над живым заходом, и это
    # ровно та гонка двух писателей в один файл, которую волна себе запрещает.
    # Признак обязан быть ПОИМЁННЫМ: не «есть какие-то окна», а «идёт окно
    # ИМЕННО ЭТОГО захода» — иначе один живой сосед заглушил бы весь сигнал.
    zahod_idyot "$(basename "$F" .md | sed 's/^kod_//')" && continue
    # 🔴 БЭКТИКИ И ЗВЁЗДОЧКИ СНИМАЮТСЯ ДО ПРОВЕРКИ. Шаблонная строка каркаса —
    # `**ВЕРДИКТ:** ` + бэктик + `<принято | доработка | отклонено>`. Образец
    # «первый непробельный символ после двоеточия не `<`» ловил на неё БЭКТИК
    # и объявлял вердикт заполненным, то есть ветка «ждёт приёмки» не сработала
    # бы НИ РАЗУ за волну (замер 02.09 09:40 на живом kod_P1-yadro.md: пустой
    # шаблон давал «непустых вердиктов: 1»).
    PR=$(sekcia "$F" "## ФАЗА ПРИ" | tr -d '`*')
    printf '%s' "$PR" | grep -qE 'ВЕРДИКТ:[[:space:]]*[^[:space:]<]' && continue
    echo "$(date '+%H:%M:%S') · ✅ ЖДЁТ ПРИЁМКИ: $(basename "$F")" >> "$LOG"; exit 0
  done <<< "$(fajly_volny)"

  # ── СОБЫТИЕ 1½: ОКОН СТАЛО МЕНЬШЕ ⇒ заход вернулся, есть что принимать.
  # Замер владельца 02.09: тринадцать пауз длиннее 15 минут, 284 минуты суммарно,
  # и БОЛЬШИНСТВО ровно по шагу будильника — голова просыпалась по звонку, а не
  # по событию. Событие «отчёт закрыт хэшем» (СОБЫТИЕ 1) ловит только аккуратно
  # закрывшийся заход; оборвавшийся не закрывает ничего и до конца тика невидим.
  # Убыль окон ловит ОБА исхода за 60 с.
  # 🔴 СЧИТАЕТСЯ ТОЛЬКО ПОСЛЕ GRACE: сразу после взведения окно ещё поднимается,
  # и незрелый счёт дал бы убыль на пустом месте.
  if [ "$PROSHLO" -ge "$GRACE" ]; then
    OKON1=$(okon)
    if [ "$OKON1" -lt "$OKON0" ] && [ "$OKON1" -gt 0 ]; then
      echo "$(date '+%H:%M:%S') · 🔔 ОКОН СТАЛО МЕНЬШЕ: ${OKON0}→${OKON1} — заход вернулся, есть что принимать" >> "$LOG"
      exit 4
    fi
  fi

  # ── СОБЫТИЕ 2: ОБРЫВ. Судим не «стало меньше окон», а СОСТОЯНИЕ: окон нет,
  #    а незакрытый заход есть. Разностная форма пропускала обрыв, случившийся
  #    до первого замера, и падала на «0\n0» (красный блок выше).
  if [ "$PROSHLO" -ge "$GRACE" ] && [ "$(okon)" -eq 0 ]; then
    while IFS= read -r F; do
      [ -e "$F" ] || continue
      # 🔴 ОБРЫВ ТОЛЬКО У ТОГО, КТО ЗАПУСКАЛСЯ. Незапущенный заход «не закрыт»
      # по построению — их в волне на шестнадцать позиций всегда большинство.
      # Замер 02.09 13:36: будильник объявил ОБРЫВ по `kod_P10-ekspluatacia.md`,
      # которую я вообще не пускал, и увёл голову диагностировать несуществующий
      # сбой, пока настоящее событие (отказ бесплатного пула на P9) стояло рядом.
      # Признак «запускался» — существование его лога: его создаёт `tee` в
      # стартовой строке, первым же байтом.
      T=$(basename "$F" .md); T=${T#kod_}
      [ -e "/tmp/zahod-$T.log" ] || continue
      zahod_zakryt "$F" && continue
      echo "$(date '+%H:%M:%S') · 🔴 ОБРЫВ: окон нет, а $(basename "$F") запускался и не закрыт — нужен добор" >> "$LOG"
      exit 2
    done <<< "$(fajly_volny)"
  fi

  [ "$PROSHLO" -ge "$TIK" ] && { echo "$(date '+%H:%M:%S') · · тик без событий · окон $(okon)" >> "$LOG"; exit 3; }
done
