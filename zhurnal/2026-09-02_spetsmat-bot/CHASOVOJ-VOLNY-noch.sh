#!/bin/bash
# ═══════════════════════════════════════════════════════════════════════════
# ЧАСОВОЙ ВОЛНЫ noch. Одна обязанность, и она про МОЮ ЖЕ голову.
#
# 🔴 ЗАЧЕМ. Механика перенята у волн 6–9 (`disciplina/_studio/zhurnal/
# 2026-08-20_poryadok-v-metaskillah/STOROZH-VOLNY.sh`, решение владельца 02.09).
# Диагноз оттуда, дословно и буквально применимый: СЕССИЯ МЕЖДУ ХОДАМИ НЕ
# СУЩЕСТВУЕТ. «Проверяй каждые 10 минут» исполняется как несколько проверок
# ВНУТРИ ОДНОГО хода, после чего ход кончается — снаружи это неотличимо от
# ожидания. Ждать умеет только ПРОЦЕСС, переживающий сессию. ЦЕНА, замерена
# соседями: две волны из четырёх простояли, не начав работу, и обе считали,
# что ждут.
#
# 🔴 ЧЕМ ЭТОТ ЧАСОВОЙ ОТЛИЧАЕТСЯ ОТ СОСЕДСКОГО. Соседский `STOROZH-VOLNY.sh`
# в обязанности 2 ЯВНО пропускает свою волну («свою волну ведёт своя сессия»)
# и держит закрытый список `VSE_VOLNY` четырёх волн репозитория disciplina.
# Волна noch живёт в ДРУГОМ репозитории и в тот список не входит —
# значит поднимать её при смерти головы некому. Это ровно та слепая зона,
# которую `skills/disciplina-orkestrator/SKILL.md` объявляет своей первой:
# «единственный наблюдатель снаружи сессии сегодня — владелец».
# Здесь она закрыта: часовой смотрит за МОЕЙ головой и поднимает ЕЁ.
#
# 🔴 ЗАПУСК — ТОЛЬКО ТАК, иначе умрёт вместе с сессией:
#   nohup bash .../CHASOVOJ-VOLNY-noch.sh >/dev/null 2>&1 & disown
#   Отвязку проверять ТОЛЬКО ОТДЕЛЬНЫМ вызовом, после выхода запускавшей
#   оболочки: `ps -o ppid= -p <pid>` → 1. Проверка в том же шелле отвечает
#   уверенно и неверно (замер соседей 02.09 08:15).
#
# 🔴 ЧЕМ ЧАСОВОЙ ДОКАЗЫВАЕТСЯ. Не словом «я его поставил», а РОСТОМ ФАЙЛА-ПУЛЬСА.
# Поставил — проверь ДВАЖДЫ с интервалом больше периода круга, что номер круга
# и метка времени сдвинулись. Не сдвинулись — часового НЕТ, как бы он ни
# выглядел в отчёте. Жив был и тот сторож, который никого не будил.
# ═══════════════════════════════════════════════════════════════════════════
set -u
KOREN="$HOME/Documents/GitHub/spetsmat-bot"
ARKA="$KOREN/zhurnal/2026-09-02_spetsmat-bot"

PERIOD_SEK=300
MERTVA_MIN=45           # сердце молчит столько — голова считается умершей
# 🔴 БЫЛ 45, ПОДНЯТ ДО 90 УТРОМ 02.09, ВОЗВРАЩЁН ВЛАДЕЛЬЦЕМ В 17:1x. Подъём был
# осознанным: контекст головы был велик, ходы длинны, а сердце билось РАЗ В ХОД —
# при 45 минутах часовой поднял бы вторую голову поверх живой, и два писателя
# пошли бы в одни файлы. Оба основания истекли в тот же день: сердце бьётся
# КАЖДЫМ обращением к Bash, а будильник звонит каждые 5 минут. Молчание в 45
# минут теперь означает смерть, а не долгий ход. Цена возврата названа
# владельцем: при 90 мёртвую голову замечают ВДВОЕ ПОЗЖЕ.
PODYOMOV_MAX=2          # больше — петля, нужен человек
PROSTOJ_MIN=10          # 🔴 ПРОСТОЙ ≠ СМЕРТЬ. Сердце молчит столько И будильников
                        # нет ни одного — голова жива, но разбудить её нечем.
                        # Просьба владельца 02.09: «раз в 10 минут просыпаться».

PULS="$ARKA/PULS-CHASOVOGO-noch.log"
SERDCE="$ARKA/SERDCE-VOLNY-noch.md"
LIST="$ARKA/PODYOM-VOLNY-noch.md"
MANDAT="$ARKA/mandate_volna-noch.md"
ZAMKI="$ARKA/.chasovoj-zamki"
mkdir -p "$ZAMKI"

mtime() { stat -f %m "$1" 2>/dev/null || stat -c %Y "$1" 2>/dev/null || echo 0; }
puls()  { echo "$(date '+%F %T') $*" >> "$PULS"; }

# 🔴 ЧАСОВОЙ НЕ МОЖЕТ РАЗБУДИТЬ ЖИВУЮ ГОЛОВУ — он вне сессии, и его единственный
# рычаг, `claude -p`, поднимает ВТОРУЮ голову поверх живой. Будить живую умеет
# только задача оснастки, чей ВЫХОД и есть сигнал. Но отказ, случившийся 02.09
# ДВАЖДЫ (36 минут в 16:19 и 43 минуты в 19:39), выглядит совершенно определённо:
# СЕРДЦЕ МОЛЧИТ И БУДИЛЬНИКОВ НЕ ЗАВЕДЕНО НИ ОДНОГО. Голова жива и не работает,
# и сама себя не разбудит, потому что будить её нечему. Часовой этот случай
# РАСПОЗНАЁТ и зовёт ЧЕЛОВЕКА — требование владельца 02.09 20:3x «убрать память
# головы из контура». Память головы из контура БЕЗОПАСНОСТИ уходит: молчание
# перестаёт быть незамеченным.
skazat_vladelcu() {
  local SEKRET="$KOREN/secrets/bot.env" T C
  [ -f "$SEKRET" ] || return 0
  T=$(awk -F= '/^ALERT_TOKEN=/{print $2}' "$SEKRET" | tr -d ' \r\n')
  C=$(awk -F= '/^OWNER_ID=/{print $2}' "$SEKRET" | tr -d ' \r\n')
  [ -n "$T" ] && [ -n "$C" ] || return 0
  curl -s -m 20 -X POST "https://api.telegram.org/bot$T/sendMessage" \
       --data-urlencode "chat_id=$C" --data-urlencode "text=$1" >/dev/null 2>&1
}

# Будильники — задачи оснастки. Их отсутствие при молчащем сердце и есть простой.
budilnikov() {
  # 🔴 НЕ `grep -c`: ОБРАЗЕЦ НАХОДИТ САМ СЕБЯ в выводе `ps`, и счётчик НИКОГДА не
  # даёт ноль — значит ветка «простой» не сработала бы НИ РАЗУ. Замер 02.09 20:32:
  # снял все будильники, `grep -c` ответил 3. Это тот же урок, что «pgrep матчит
  # сам себя» (волна 6) и что «зона-префикс даёт ложно-зелёное»: проверка,
  # которая не может дать отрицательный ответ, не проверка.
  # Считаем строго: `bash <полный путь>/BUDILNIK-VOLNY-noch.sh <тик>`.
  ps -Ao command= 2>/dev/null | awk -v b="$ARKA/BUDILNIK-VOLNY-noch.sh" \
    '($1 == "bash" && $2 == b) { n++ } END { print n+0 }' | tr -d " \n"
}

podnyat_svoyu_golovu_esli_myortva() {
  # Признаки И-связкой, чтобы не поднять живого.
  [ -f "$LIST" ]   || { puls "подъёмного листа нет — поднимать нечем, НЕ поднимаю"; return 0; }
  [ -f "$SERDCE" ] || { puls "сердца нет — отличить «думает» от «умерла» нечем, НЕ поднимаю"; return 0; }
  grep -q '^\*\*STATUS:\*\* *`CLOSED`' "$MANDAT" 2>/dev/null && return 0
  grep -q '^\*\*STATUS:\*\* *`REFUSED`' "$MANDAT" 2>/dev/null && return 0
  pgrep -f "PODYOM-VOLNY-noch" >/dev/null 2>&1 && return 0

  local NOW TISH
  NOW=$(date +%s)
  TISH=$(( (NOW - $(mtime "$SERDCE")) / 60 ))
  [ "$TISH" -lt "$MERTVA_MIN" ] && return 0

  local SCHET_F="$ZAMKI/podyomov" SCHET=0
  [ -f "$SCHET_F" ] && SCHET=$(cat "$SCHET_F")
  if [ "$SCHET" -ge "$PODYOMOV_MAX" ]; then
    puls "⚠ голова мертва (тишина ${TISH}м), но подъёмов уже $SCHET из $PODYOMOV_MAX — НЕ поднимаю, это петля. Нужен человек."
    return 0
  fi

  # Замок атомарный: mkdir падает, если каталог есть — два часовых не поднимут две головы.
  mkdir "$ZAMKI/podnimayu" 2>/dev/null || { puls "подъём уже ведёт другой часовой, не мешаю"; return 0; }

  puls "🔴 ГОЛОВА МЕРТВА (сердце молчит ${TISH}м ≥ ${MERTVA_MIN}м, мандат открыт, подъёма в процессах нет). ПОДНИМАЮ, подъём $((SCHET+1)) из $PODYOMOV_MAX."
  echo "$((SCHET+1))" > "$SCHET_F"
  nohup claude -p --model opus --dangerously-skip-permissions "[PODYOM-VOLNY-noch] $(cat "$LIST")" >> "/tmp/podyom-noch.log" 2>&1 &
  disown 2>/dev/null || true
  sleep 30
  if pgrep -f "\[PODYOM-VOLNY-noch\]" >/dev/null 2>&1; then
    puls "✅ подъём запущен, лог /tmp/podyom-noch.log"
  else
    puls "❌ подъём НЕ поднялся — смотри /tmp/podyom-noch.log"
  fi
  rmdir "$ZAMKI/podnimayu" 2>/dev/null || true
}

puls "ЧАСОВОЙ ПОДНЯТ pid=$$ ppid=$PPID · период=${PERIOD_SEK}с · порог смерти=${MERTVA_MIN}м"

KRUG=0
while :; do
  KRUG=$((KRUG+1))
  SEJCHAS=$(date +%s)
  TISH=$(( (SEJCHAS - $(mtime "$SERDCE")) / 60 ))

  # Живые заходы волны — окна ZAPUSK-ZAHODA.sh ЭТОЙ арки.
  # 🔴 ОБРАЗЕЦ ПО ПОЛНОМУ ПУТИ ТЕРЯЛ ЖИВЫЕ ОКНА. Замер 02.09 16:57: добор P15 был
  # пущен как `cd <арка> && bash ZAPUSK-ZAHODA.sh P15-tekst opus --dobor`, и в
  # `ps` вторым полем стоит ГОЛОЕ ИМЯ. Часовой писал «окон 1» при двух живых —
  # то есть тот же класс, что «зона-префикс даёт ложно-зелёное»: образец не
  # совпал ни с чем, и молчание было принято за факт. Для строки «окон стало
  # меньше» это не косметика: недосчитанное окно даёт ЛОЖНЫЙ звонок приёмки.
  # Голое имя считаем своим только вместе с темой из наших `kod_*.md`.
  TEMY=$(for f in "$ARKA"/kod_*.md; do [ -e "$f" ] || continue; b=$(basename "$f" .md); printf '%s ' "${b#kod_}"; done)
  OKON=$(ps -Ao command= 2>/dev/null | awk -v z="$ARKA/ZAPUSK-ZAHODA.sh" -v a="$ARKA" -v temy="$TEMY" '
      BEGIN { split(temy, q, " "); for (i in q) svoi[q[i]] = 1 }
      ($1 == "bash" && ($2 == z || $2 == "ZAPUSK-ZAHODA.sh") && ($3 in svoi)) { n++ }
      (index($0, "orkestr.py " a) && index($0, "--rezhim progon")) { n++ }
      END { print n+0 }' | tr -d ' \n')
  # Заходы, чьи файлы тронуты за последние 30 минут — работа, видимая по следу.
  SVEZHIH=0
  for F in "$ARKA"/kod_*.md; do
    [ -e "$F" ] || continue
    [ $(( (SEJCHAS - $(mtime "$F")) / 60 )) -lt 30 ] && SVEZHIH=$((SVEZHIH+1))
  done

  puls "круг $KRUG · сердце молчит ${TISH}м · окон заходов $OKON · свежих kod_* $SVEZHIH"

  # ── УБЫЛЬ ОКОН = «ЕСТЬ ЧТО ПРИНИМАТЬ». Просьба владельца 02.09 17:0x.
  # 🔴 ЧАСОВОЙ РАЗБУДИТЬ ЖИВУЮ ГОЛОВУ НЕ МОЖЕТ — он вне сессии (ppid=1), и
  # единственный его рычаг, `claude -p`, поднимает ВТОРУЮ голову поверх живой.
  # Поэтому звонит будильник (он считает то же самое каждые 60 с вместо 300),
  # а часовой ФИКСИРУЕТ факт: он переживает смерть головы, а будильник — нет.
  # Следующая голова читает пульс первым ходом и видит, что вернулось, пока её
  # предшественницы не было.
  PRED_F="$ZAMKI/okon-bylo"
  PRED=$(cat "$PRED_F" 2>/dev/null || echo "$OKON")
  case "$PRED" in ''|*[!0-9]*) PRED=$OKON ;; esac
  if [ "$OKON" -lt "$PRED" ]; then
    puls "🔔 ОКОН СТАЛО МЕНЬШЕ: ${PRED}→${OKON} — заход(ы) вернулись, ЕСТЬ ЧТО ПРИНИМАТЬ"
  fi
  echo "$OKON" > "$PRED_F"

  # ── ПРОСТОЙ ГОЛОВЫ: сердце молчит и будить её нечем.
  B=$(budilnikov)
  if [ "$TISH" -ge "$PROSTOJ_MIN" ] && [ "$B" -eq 0 ]; then
    if [ ! -f "$ZAMKI/skazano-o-prostoe" ] || \
       [ $(( SEJCHAS - $(mtime "$ZAMKI/skazano-o-prostoe") )) -gt 900 ]; then
      puls "🔔 ПРОСТОЙ ГОЛОВЫ: сердце молчит ${TISH}м и будильников НЕТ — разбудить её нечем. Зову владельца."
      skazat_vladelcu "⚠️ Оркестратор простаивает ${TISH} мин: сердце молчит, будильников не заведено ни одного — разбудить его нечем. Напишите ему в терминал, и работа продолжится. (Часовой волны noch, порог ${PROSTOJ_MIN} мин.)"
      touch "$ZAMKI/skazano-o-prostoe"
    fi
  elif [ "$B" -gt 0 ] && [ -f "$ZAMKI/skazano-o-prostoe" ]; then
    rm -f "$ZAMKI/skazano-o-prostoe"
    puls "✅ будильники снова заведены ($B) — простой кончился"
  fi

  podnyat_svoyu_golovu_esli_myortva

  sleep "$PERIOD_SEK"
done
