#!/bin/bash
# ═══════════════════════════════════════════════════════════════════════════
# БУДИЛЬНИК ВОЛНЫ sborka-bota — ОПОВЕЩЕНИЕ. Запускать ТОЛЬКО задачей оснастки
# (`run_in_background`), НЕ nohup: весь его смысл в том, что его ВЫХОД —
# сигнал голове. Под nohup он переживёт зависание приложения и НЕ РАЗБУДИТ
# НИКОГО, то есть станет бесполезен ровно в том, ради чего заведён.
#
# 🔴 ТРИ МЕХАНИЗМА ВОЛНЫ, ТРИ РАЗНЫЕ СМЕРТИ, НИ ОДИН НЕ ЗАМЕНЯЕТ ДРУГИХ:
#   1. CHASOVOJ-sborka-bota.sh — nohup, ppid=1: переживает зависание,
#      поднимает мёртвую голову через `claude -p`. НЕ БУДИТ живую.
#   2. ЗАХОДЫ под nohup            — переживают сессию, работают сами.
#   3. ЭТОТ файл                   — задача оснастки: будит, но умирает
#      вместе с приложением.
# Цена смешения ролей оплачена соседями 02.09 08:10: всё длящееся перевели на
# nohup и тем же движением сняли единственный механизм, которым сессия узнаёт
# о событии. Работа шла, а разбудить голову было НЕЧЕМ — снаружи неотличимо
# от мёртвой головы.
#
# 🔴 ОДНОРАЗОВЫЙ. После каждого срабатывания ВЗВЕСТИ ЗАНОВО.
#
# КОДЫ ВЫХОДА:
#   0 — заход ЖДЁТ ПРИЁМКИ (отчёт закрыт хэшем, вердикта нет)
#   1 — 🔴 ПУЛЬС ЧАСОВОГО НЕ РАСТЁТ: часового НЕТ, что бы ни говорили процессы
#   2 — окно захода закрылось, а отчёта с хэшем нет: обрыв, нужен добор
#   3 — тик без событий: взвести заново
# ═══════════════════════════════════════════════════════════════════════════
set -u
ARKA="$HOME/Documents/GitHub/spetsmat-bot/zhurnal/2026-09-02_spetsmat-bot"
PULS="$ARKA/PULS-CHASOVOGO-sborka-bota.log"
LOG=/tmp/budilnik-sborka-bota.log
TIK=${1:-2400}          # холостой потолок
SVERKA=${2:-420}        # через сколько секунд сверить РОСТ пульса (> периода часового 300с)

krugov () { grep -c '^....-..-.. ..:..:.. круг ' "$PULS" 2>/dev/null || echo 0; }
metka ()  { stat -f %m "$PULS" 2>/dev/null || stat -c %Y "$PULS" 2>/dev/null || echo 0; }
okon ()   { pgrep -f "$ARKA/ZAPUSK-ZAHODA.sh" 2>/dev/null | grep -vc BUDILNIK || echo 0; }

K0=$(krugov); M0=$(metka); O0=$(okon)
echo "$(date '+%H:%M:%S') · взведён · пульс: кругов $K0, метка $M0 · окон $O0" >> "$LOG"
NACHALO=$(date +%s); SVERENO=0

while :; do
  sleep 60
  PROSHLO=$(( $(date +%s) - NACHALO ))

  # ── ГЛАВНОЕ: часовой доказывается РОСТОМ ПУЛЬСА, а не наличием процесса.
  #    Жив был и тот сторож, который никого не будил.
  if [ "$SVERENO" -eq 0 ] && [ "$PROSHLO" -ge "$SVERKA" ]; then
    K1=$(krugov); M1=$(metka)
    if [ "$K1" -gt "$K0" ] && [ "$M1" -gt "$M0" ]; then
      echo "$(date '+%H:%M:%S') · ✅ ПУЛЬС РАСТЁТ: кругов $K0→$K1 за ${PROSHLO}с — часовой ЕСТЬ" >> "$LOG"
      SVERENO=1
    else
      echo "$(date '+%H:%M:%S') · 🔴 ПУЛЬС НЕ РАСТЁТ за ${PROSHLO}с: кругов $K0→$K1, метка $M0→$M1 — ЧАСОВОГО НЕТ" >> "$LOG"
      exit 1
    fi
  fi

  # ── заход закрыл отчёт хэшем, а вердикта в ФАЗЕ ПРИЁМКИ нет ⇒ ждёт приёмки
  for F in "$ARKA"/kod_*.md; do
    [ -e "$F" ] || continue
    OT=$(awk '/^## ОТЧ[ЕЁ]Т/{x=1;next} /^## /{x=0} x' "$F")
    printf '%s' "$OT" | grep -qoE '`[0-9a-f]{7,40}`' || \
      printf '%s' "$OT" | grep -qiE 'КОММИТА НЕТ|NO COMMIT' || continue
    PR=$(awk '/^## ФАЗА ПРИ[ЕЁ]МКИ/{x=1;next} /^## /{x=0} x' "$F")
    printf '%s' "$PR" | grep -qE 'ВЕРДИКТ:[[:space:]]*[^[:space:]<]' && continue
    echo "$(date '+%H:%M:%S') · ✅ ЖДЁТ ПРИЁМКИ: $(basename "$F")" >> "$LOG"; exit 0
  done

  # ── окно закрылось, а отчёта нет ⇒ обрыв
  O1=$(okon)
  if [ "$O0" -gt 0 ] && [ "$O1" -lt "$O0" ]; then
    echo "$(date '+%H:%M:%S') · 🔴 ОКОН СТАЛО МЕНЬШЕ ($O0→$O1) без отчёта с хэшем — обрыв, нужен добор" >> "$LOG"; exit 2
  fi
  O0=$O1

  [ "$PROSHLO" -ge "$TIK" ] && { echo "$(date '+%H:%M:%S') · · тик без событий" >> "$LOG"; exit 3; }
done
